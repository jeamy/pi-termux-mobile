const norm = (s) => String(s).replace(/\s+/g, ' ').trim();
const INDEX = new Map();
for (const pair of PAIRS) for (const s of pair) if (!INDEX.has(norm(s))) INDEX.set(norm(s), pair);

function stored() { try { return localStorage.getItem('pi-lang'); } catch { return null; } }
export const lang = stored() === 'de' || stored() === 'en' ? stored()
  : String(globalThis.navigator?.language || '').toLowerCase().startsWith('de') ? 'de' : 'en';
/** The locale for dates and numbers. */
export const locale = lang === 'de' ? 'de-AT' : 'en-GB';

/** The text in the chosen language; `{name}` takes vars.name. Unknown text comes back as it is. */
export function t(text, vars) {
  const pair = INDEX.get(norm(text));
  const out = pair ? pair[lang === 'de' ? 1 : 0] : String(text);
  return vars ? out.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k] ?? '') : m)) : out;
}

/** Whether the table knows the text (for the tests). */
export const known = (text) => INDEX.has(norm(text));
export const pairs = PAIRS;

export function setLang(next) {
  try { localStorage.setItem('pi-lang', next); } catch {}
  location.reload();
}

const SKIP = new Set(['SCRIPT', 'STYLE', 'PRE', 'TEXTAREA', 'CODE']);
const ATTRS = ['placeholder', 'title', 'aria-label'];

/** Translates the static page: run once, before the page's scripts write anything into it. */
export function applyI18n(root = document) {
  document.documentElement.lang = lang;
  for (const el of root.querySelectorAll('[data-i18n-html]')) {
    const pair = INDEX.get(norm(el.innerHTML));
    if (pair) el.innerHTML = pair[lang === 'de' ? 1 : 0];
  }
  const walker = document.createTreeWalker(root.documentElement ?? root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      for (let p = node.parentElement; p; p = p.parentElement) {
        if (SKIP.has(p.tagName) || p.hasAttribute('data-i18n-html')) return NodeFilter.FILTER_REJECT;
      }
      return norm(node.data) ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_SKIP;
    },
  });
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const pair = INDEX.get(norm(node.data));
    if (!pair) continue;
    const [, lead, , tail] = /^(\s*)([\s\S]*?)(\s*)$/.exec(node.data);
    node.data = lead + pair[lang === 'de' ? 1 : 0] + tail;
  }
  for (const attr of ATTRS) {
    for (const el of root.querySelectorAll(`[${attr}]`)) {
      const pair = INDEX.get(norm(el.getAttribute(attr)));
      if (pair) el.setAttribute(attr, pair[lang === 'de' ? 1 : 0]);
    }
  }
}
